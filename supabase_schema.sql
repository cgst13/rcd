-- ROW LEVEL SECURITY (RLS) POLICIES
-- Regular 'user' sees/modifies only their own data.
-- 'admin' can view and monitor all collections and reports.
-- ================================================================

-- Enable RLS on all tables
alter table public.rcd_profiles enable row level security;
alter table public.rcd_reports enable row level security;
alter table public.rcd_collections enable row level security;
alter table public.rcd_rpt_collections enable row level security;
alter table public.rcd_account_codes enable row level security;
alter table public.rcd_signatories enable row level security;

-- 1. PROFILES POLICIES (rcd_profiles)
-- Users see their own profile, Admins see and manage all profiles (CRUD)
drop policy if exists "Users and Admins view profiles" on public.rcd_profiles;
drop policy if exists "Users can view profiles" on public.rcd_profiles;
drop policy if exists "Users can view their own profile" on public.rcd_profiles;
create policy "Users and Admins view profiles"
  on public.rcd_profiles for select
  using (auth.uid() = id or public.is_admin());

drop policy if exists "Users and Admins insert profiles" on public.rcd_profiles;
create policy "Users and Admins insert profiles"
  on public.rcd_profiles for insert
  with check (auth.uid() = id or public.is_admin());

drop policy if exists "Users and Admins update profiles" on public.rcd_profiles;
drop policy if exists "Users can update profiles" on public.rcd_profiles;
drop policy if exists "Users can update their own profile" on public.rcd_profiles;
create policy "Users and Admins update profiles"
  on public.rcd_profiles for update
  using (auth.uid() = id or public.is_admin());

drop policy if exists "Admins can delete profiles" on public.rcd_profiles;
drop policy if exists "Users and Admins delete profiles" on public.rcd_profiles;
create policy "Admins can delete profiles"
  on public.rcd_profiles for delete
  using (public.is_admin());


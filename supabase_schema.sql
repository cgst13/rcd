-- ================================================================
-- SUPABASE DATABASE SCHEMA FOR RCD (Report of Collections & Deposits)
-- Role-Based Access: 'user' (Collector) & 'admin' (Administrator)
-- Admin can monitor all collections, reports, and users
-- ================================================================

-- 1. EXTENSIONS
create extension if not exists "uuid-ossp";

-- 2. USER PROFILES TABLE (rcd_profiles)
create table if not exists public.rcd_profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  email text not null,
  full_name text,
  role text default 'user' not null, -- 'user' (Collector) or 'admin' (Administrator)
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- Helper function to check if current user is an Admin
create or replace function public.is_admin()
returns boolean as $$
begin
  return exists (
    select 1 from public.rcd_profiles
    where id = auth.uid() and lower(role) in ('admin', 'administrator')
  );
end;
$$ language plpgsql security definer;

-- Trigger to automatically create a profile when a new user signs up in Supabase Auth
create or replace function public.handle_new_rcd_user()
returns trigger as $$
begin
  insert into public.rcd_profiles (id, email, full_name, role)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'role', 'user')
  )
  on conflict (id) do update
  set 
    email = excluded.email,
    full_name = coalesce(excluded.full_name, public.rcd_profiles.full_name),
    role = coalesce(excluded.role, public.rcd_profiles.role),
    updated_at = now();
  return new;
end;
$$ language plpgsql security definer;

-- Drop trigger if exists and recreate
drop trigger if exists on_auth_user_created_rcd on auth.users;
create trigger on_auth_user_created_rcd
  after insert on auth.users
  for each row execute procedure public.handle_new_rcd_user();

-- 3. RCD REPORTS TABLE (rcd_reports)
create table if not exists public.rcd_reports (
  id uuid default gen_random_uuid() primary key,
  user_id uuid references auth.users(id) on delete cascade default auth.uid() not null,
  report_number text not null,
  date date not null default current_date,
  collector_name text not null,
  fund_type text not null check (fund_type in ('General Fund', 'Trust Fund', 'SEF')),
  collections jsonb not null default '[]'::jsonb,
  total_collection numeric(14, 2) not null default 0,
  deposits jsonb not null default '[]'::jsonb,
  total_deposit numeric(14, 2) not null default 0,
  status text not null default 'Draft' check (status in ('Draft', 'Submitted', 'Verified')),
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists idx_rcd_reports_user_id on public.rcd_reports(user_id);
create index if not exists idx_rcd_reports_date on public.rcd_reports(date);

-- 4. GENERAL COLLECTIONS TABLE (rcd_collections)
create table if not exists public.rcd_collections (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade default auth.uid() not null,
  af_no text,
  or_no text,
  payor text,
  sub_category text,
  main_category text,
  account_code text,
  amount numeric(14, 2) not null default 0,
  date date default current_date,
  remarks text,
  created_at timestamptz default now()
);

create index if not exists idx_rcd_collections_user_id on public.rcd_collections(user_id);
create index if not exists idx_rcd_collections_date on public.rcd_collections(date);

-- 5. REAL PROPERTY TAX (RPT) COLLECTIONS TABLE (rcd_rpt_collections)
create table if not exists public.rcd_rpt_collections (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade default auth.uid() not null,
  af56_id text,
  or_number text,
  payor text,
  barangay text,
  land_name text,
  td_number text,
  years_paid text,
  amount numeric(14, 2) not null default 0,
  date date default current_date,
  remarks text,
  created_at timestamptz default now()
);

create index if not exists idx_rcd_rpt_collections_user_id on public.rcd_rpt_collections(user_id);
create index if not exists idx_rcd_rpt_collections_date on public.rcd_rpt_collections(date);

-- 6. ACCOUNT CODES TABLE (rcd_account_codes)
create table if not exists public.rcd_account_codes (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade default auth.uid(),
  main_category text not null,
  sub_category text not null,
  code text not null,
  created_at timestamptz default now()
);

create index if not exists idx_rcd_account_codes_user_id on public.rcd_account_codes(user_id);

-- 7. SIGNATORIES TABLE (rcd_signatories)
create table if not exists public.rcd_signatories (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade default auth.uid(),
  full_name text not null,
  position text not null,
  department text not null,
  remarks text,
  created_at timestamptz default now()
);

create index if not exists idx_rcd_signatories_user_id on public.rcd_signatories(user_id);

